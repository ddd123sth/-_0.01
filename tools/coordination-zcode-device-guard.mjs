// Device-local independent guard for one bounded P01 window on 003.
//
// The host pushes and starts this script through `su`, then has no further role:
// the script keeps its own heartbeat, blocks only the app's own non-443 world
// sockets for the armed interval, removes exactly those rules at the absolute
// deadline, observes recovery until close, then delivers the durable native STOP through the app's own
// loopback API. It therefore still returns the device when the host probe dies,
// when the host adb forward is gone, or when the host command channel is
// blocked — the failure domain that lost 38 STOP attempts in B2 was the host.
//
// Bounds:
//  - every value is validated here: one window UUID, one control command UUID,
//    one account ref, numeric epochs, one 10078-style app uid read on device;
//  - rules are added only for sockets that /proc/net/tcp reports for this app
//    uid, never 443, never loopback/private, and only in state 01/02; every
//    added tuple is appended to rules.txt and removed at the deadline;
//  - the STOP is delivered only when the native control sequence is still the
//    one observed when the window was armed. A newer control (a user STOP or a
//    user START) owns the device and this old window records `skipped` instead
//    of stopping a newer decision. The server also supersedes an older command
//    by control_seq, so the guard cannot win that race by arriving late;
//  - the script exits at the hard deadline whatever happens, and writes one
//    receipt per fact (heartbeat, blocked tuples, rules-clean, stop outcome).
//
// Modes
//   selftest  build/inspect the script only, no device access
//   arm       push, launch, and prove the guard is alive and heartbeating
//   read      read back the receipts of one window
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ADB = process.env.GARDEN_ANDROID_ADB || 'C:/leidian/LDPlayer14/adb.exe';
const PACKAGE = 'online.ainiannian.wujinxia';
const SERIALS = new Set(['emulator-5554', 'emulator-5556', 'emulator-5558']);
const REMOTE_ROOT = '/data/local/tmp/r8z-b3';
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;
const OWNER = /^[A-Za-z0-9_.:-]{1,512}$/;
const ACCOUNT = /^[0-9]{1,20}$/;
const MAX_AHEAD_MS = 17 * 60_000;

const fail = (code, message = code) => Object.assign(new Error(message), { code });
const num = (value, name, min, max) => {
  const parsed = Number(value);
  if (!Number.isSafeInteger(parsed) || parsed < min || parsed > max) throw fail('ARGS', name + ' is out of range');
  return parsed;
};
const text = (value, name, pattern) => {
  const parsed = String(value ?? '');
  if (!pattern.test(parsed)) throw fail('ARGS', name + ' is invalid');
  return parsed;
};
const shellQuote = value => "'" + String(value).replaceAll("'", "'\\''") + "'";

export function normalizeArmArgs(input = {}) {
  const now = Date.now();
  const args = {
    windowId: text(input.windowId, 'windowId', UUID),
    commandId: text(input.commandId, 'commandId', UUID),
    serial: text(input.serial || 'emulator-5558', 'serial', /^emulator-555[468]$/),
    accountRef: text(input.accountRef, 'accountRef', ACCOUNT),
    ownerRef: text(input.ownerRef, 'ownerRef', OWNER),
    scan: input.scan === true || input.scan === 'true',
    startAtMs: num(input.startAtMs, 'startAtMs', 1, Number.MAX_SAFE_INTEGER),
    deadlineMs: num(input.deadlineMs, 'deadlineMs', 1, Number.MAX_SAFE_INTEGER),
    closeMs: num(input.closeMs, 'closeMs', 1, Number.MAX_SAFE_INTEGER),
    hardMs: num(input.hardMs, 'hardMs', 1, Number.MAX_SAFE_INTEGER),
    clockOffsetMs: num(input.clockOffsetMs ?? 0, 'clockOffsetMs', -86400000, 86400000),
    armedControlSeq: num(input.armedControlSeq, 'armedControlSeq', 0, Number.MAX_SAFE_INTEGER),
    armedGeneration: text(input.armedGeneration, 'armedGeneration', UUID),
  };
  if (!SERIALS.has(args.serial)) throw fail('ARGS', 'serial outside this project');
  if (!(now < args.startAtMs && args.startAtMs < args.deadlineMs && args.deadlineMs < args.closeMs &&
      args.closeMs + 30000 <= args.hardMs && args.closeMs - now <= 15 * 60_000 && args.hardMs - now <= MAX_AHEAD_MS))
    throw fail('ARGS', 'window requires now < start < restore < close, with at least 30s before hard');
  return args;
}

export function buildGuardScript(args) {
  const windowDir = `${REMOTE_ROOT}/${args.windowId}`;
  return `#!/system/bin/sh
# R8 Zcode B3 device-local guard ${args.windowId}
# Generated by tools/coordination-zcode-device-guard.mjs; runs without the host.
PKG=${shellQuote(PACKAGE)}
WID=${shellQuote(args.windowId)}
CMD=${shellQuote(args.commandId)}
ACC=${shellQuote(args.accountRef)}
OWNER=${shellQuote(args.ownerRef)}
START_AT=${args.startAtMs - (args.clockOffsetMs || 0)}
DEADLINE=${args.deadlineMs - (args.clockOffsetMs || 0)}
CLOSE=${args.closeMs - (args.clockOffsetMs || 0)}
HARD=${args.hardMs - (args.clockOffsetMs || 0)}
ARMED_SEQ=${args.armedControlSeq}
ARMED_GEN=${shellQuote(args.armedGeneration)}
SCAN=${args.scan ? 1 : 0}
EARLY=0
OUT=${shellQuote(windowDir)}
SESS=/data/data/$PKG/files/engine-session.json
CTRL=/data/data/$PKG/files/data/native-stop-control.json
DB=/data/data/$PKG/files/data/garden.db
IPT=/system/bin/iptables

mkdir -p "$OUT" || exit 3
TS() { date +%s%3N; }
note() { printf '%s %s\\n' "$(TS)" "$1" >> "$OUT/events.log"; }
beat() { TS > "$OUT/heartbeat"; }
budget_seconds() {
  left=$((HARD-$(TS)))
  [ "$left" -gt 1000 ] || return 1
  cap=$1
  secs=$((left/1000))
  [ "$secs" -le "$cap" ] || secs=$cap
  printf '%s' "$secs"
}

ipt() {
  budget=$(budget_seconds 3) || return 1
  timeout "$budget" "$IPT" "$@"
}
: > "$OUT/events.log"
: > "$OUT/rules.txt"
: > "$OUT/blocked-events.txt"
echo "$$" > "$OUT/guard-pid"
echo armed > "$OUT/state"
note "armed start=$START_AT restore=$DEADLINE close=$CLOSE hard=$HARD seq=$ARMED_SEQ gen=$ARMED_GEN scan=$SCAN acc=$ACC"
beat

APPUID=$(stat -c %u /data/data/$PKG 2>/dev/null)
if [ -z "$APPUID" ]; then echo "missing-app-uid" > "$OUT/app-uid"; else echo "$APPUID" > "$OUT/app-uid"; fi

scan_and_block() {
  [ "$SCAN" = "1" ] || return 0
  [ -n "$APPUID" ] || return 0
  cat /proc/net/tcp 2>/dev/null | awk -v uid="$APPUID" '
    function h2d(s,   i,c,v){ v=0; for(i=1;i<=length(s);i++){ c=tolower(substr(s,i,1)); v=v*16 + (c>="0" && c<="9" ? c+0 : index("abcdef",c)+9) } return v }
    NR>1 {
      if (NF<10) next
      remote=$3; st=$4; owner=$8
      if (owner != uid) next
      if (st != "01" && st != "02") next
      split(remote, r, ":")
      ip1=h2d(substr(r[1],7,2)); ip2=h2d(substr(r[1],5,2)); ip3=h2d(substr(r[1],3,2)); ip4=h2d(substr(r[1],1,2))
      port=h2d(r[2])
      if (port == 443) next
      if (ip1 == 127 || ip1 == 10) next
      if (ip1 == 172 && ip2 >= 16 && ip2 <= 31) next
      if (ip1 == 192 && ip2 == 168) next
      print ip1"."ip2"."ip3"."ip4, port, st
    }' | while read ip port st; do
      [ -n "$ip" ] || continue
      grep -qx "$ip $port" "$OUT/rules.txt" 2>/dev/null && continue
      if ipt -I OUTPUT 1 -d "$ip" -p tcp --dport "$port" -j DROP 2>/dev/null; then
        ipt -I INPUT 1 -s "$ip" -p tcp --sport "$port" -j DROP 2>/dev/null
        printf '%s %s\\n' "$ip" "$port" >> "$OUT/rules.txt"
        printf '%s %s %s %s\\n' "$(TS)" "$ip" "$port" "$st" >> "$OUT/blocked-events.txt"
        note "blocked $ip:$port state=$st"
      fi
    done
}

# Phase-wait: only heartbeat until the agreed fault start. STOP_NOW is the
# host's early-abort request; it can only shorten the window, never extend it.
while :; do
  if [ -f "$OUT/STOP_NOW" ]; then EARLY=1; break; fi
  now=$(TS)
  [ "$now" -ge "$START_AT" ] && break
  beat
  sleep 1
done
note "fault-start"
echo fault-active > "$OUT/state"

while :; do
  if [ -f "$OUT/STOP_NOW" ]; then EARLY=1; break; fi
  now=$(TS)
  [ "$now" -ge "$DEADLINE" ] && break
  [ "$now" -ge "$HARD" ] && break
  beat
  scan_and_block
  sleep 1
done
if [ "$EARLY" = 1 ]; then note "early-restore-requested"; else note "restore-deadline-reached"; fi
echo restoring > "$OUT/state"
beat

# 1) Rules first: they must come back even when the STOP below cannot be sent.
while read ip port; do
  [ -n "$ip" ] || continue
  ipt -D OUTPUT -d "$ip" -p tcp --dport "$port" -j DROP 2>/dev/null
  ipt -D INPUT -s "$ip" -p tcp --sport "$port" -j DROP 2>/dev/null
  ipt -D OUTPUT -d "$ip" -p tcp --dport "$port" -j DROP 2>/dev/null
  ipt -D INPUT -s "$ip" -p tcp --sport "$port" -j DROP 2>/dev/null
  note "unblocked $ip:$port"
done < "$OUT/rules.txt"
query_ok=1
ipt -S OUTPUT > "$OUT/rules-after-OUTPUT.txt" 2>&1 || query_ok=0
ipt -S INPUT > "$OUT/rules-after-INPUT.txt" 2>&1 || query_ok=0
left=0
while read ip port; do
  [ -n "$ip" ] || continue
  grep -qF -- "-d $ip " "$OUT/rules-after-OUTPUT.txt" && left=$((left+1))
  grep -qF -- "-s $ip " "$OUT/rules-after-INPUT.txt" && left=$((left+1))
done < "$OUT/rules.txt"
if [ "$query_ok" != 1 ]; then echo unverified > "$OUT/rules-clean";
elif [ "$left" -eq 0 ]; then echo clean > "$OUT/rules-clean"; else echo "dirty:$left" > "$OUT/rules-clean"; fi
note "rules checked left=$left"
TS > "$OUT/rules-restored-at"

# Network restoration leaves the running intent intact until final close.
echo recovery-observation > "$OUT/state"
while :; do
  if [ -f "$OUT/STOP_NOW" ]; then EARLY=1; break; fi
  now=$(TS)
  [ "$now" -ge "$CLOSE" ] && break
  [ "$now" -ge "$HARD" ] && break
  beat
  sleep 1
done
if [ "$EARLY" = 1 ]; then echo early-stop-file > "$OUT/stop-trigger"; else echo close > "$OUT/stop-trigger"; fi
note "stop-trigger $(cat "$OUT/stop-trigger")"
TS > "$OUT/stop-started-at"


# 2) Durable STOP. The host and device use the same command UUID; either
# may win the race, but a different newer user decision must never be stopped.
seq_now=$(grep -o '"controlSeq":[0-9]*' "$CTRL" 2>/dev/null | head -1 | cut -d: -f2)
cmd_now=$(grep -o '"commandId":"[^"]*"' "$CTRL" 2>/dev/null | head -1 | cut -d'"' -f4)
gen_now=$(grep -o '"instanceRef":"[^"]*"' "$CTRL" 2>/dev/null | head -1 | cut -d'"' -f4)
printf 'armedSeq=%s currentSeq=%s armedGen=%s currentGen=%s checkedAt=%s\\n' \\
  "$ARMED_SEQ" "$seq_now" "$ARMED_GEN" "$gen_now" "$(TS)" > "$OUT/stop-precheck.txt"
verify_stop=0
if [ "$seq_now" != "$ARMED_SEQ" ] && [ "$cmd_now" != "$CMD" ]; then
  echo "skipped:CONTROL_SEQ_MOVED" > "$OUT/stop-outcome"
  note "stop skipped control seq moved $ARMED_SEQ->$seq_now"
elif [ "$cmd_now" = "$CMD" ]; then
  echo already-committed > "$OUT/stop-outcome"
  verify_stop=1
elif [ ! -f "$SESS" ]; then
  echo "skipped:NO_SESSION" > "$OUT/stop-outcome"
else
  port=$(grep -o '"port":[0-9]*' "$SESS" | head -1 | cut -d: -f2)
  token=$(grep -o '"token":"[a-f0-9]*"' "$SESS" | head -1 | cut -d'"' -f4)
  if [ -z "$port" ] || [ -z "$token" ]; then
    echo "skipped:SESSION_UNREADABLE" > "$OUT/stop-outcome"
  else
    budget=$(budget_seconds 10) || { echo hard-budget-exhausted > "$OUT/stop-outcome"; exit 4; }
    resp=$(curl -s -m "$budget" -X POST -H "Authorization: Bearer $token" -H 'Content-Type: application/json' \\
      -d "{\\"commandId\\":\\"$CMD\\",\\"requestedAtMs\\":$(TS)}" "http://127.0.0.1:$port/api/local/stop-all" 2>&1)
    printf '%s' "$resp" > "$OUT/stop-response.json"
    case "$resp" in
      *'"stopCommitted":true'*) echo sent > "$OUT/stop-outcome"; verify_stop=1 ;;
      *) echo failed > "$OUT/stop-outcome" ;;
    esac
  fi
fi
i=0
while [ "$verify_stop" = 1 ] && [ "$i" -lt 10 ]; do
  i=$((i+1))
  budget=$(budget_seconds 5) || { echo hard-budget-exhausted > "$OUT/stop-verified"; break; }
  left=$(timeout "$budget" sqlite3 -readonly -cmd ".timeout 1000" "$DB" \\
    "SELECT count(*) FROM backend_run_intents WHERE desired_running=1 OR state<>'STOPPED';" 2>/dev/null)
  cmd_now=$(grep -o '"commandId":"[^"]*"' "$CTRL" | head -1 | cut -d'"' -f4)
  if [ "$left" = 0 ] && [ "$cmd_now" = "$CMD" ] &&
      grep -q '"stopCommitted":true' "$CTRL" && grep -q '"cleanupComplete":true' "$CTRL"; then
    echo stopped > "$OUT/stop-verified"
    break
  fi
  echo "pending:$left" > "$OUT/stop-verified"
  budget=$(budget_seconds 2) || break
  sleep 1
done
note "stop outcome=$(cat "$OUT/stop-outcome" 2>/dev/null)"
echo done > "$OUT/state"
beat
exit 0
`;
}

const adb = (serial, args, { input = undefined, timeout = 20000 } = {}) =>
  execFileSync(ADB, ['-s', serial, ...args], { encoding: 'utf8', timeout, windowsHide: true, ...(input === undefined ? {} : { input }) });

export function buildGuardLaunchCommand(args) {
  const localHardMs = args.hardMs - args.clockOffsetMs;
  const command = `command -v timeout >/dev/null || exit 4; command -v setsid >/dev/null || exit 4; ` +
    `remaining=$(((${localHardMs}-$(date +%s%3N))/1000)); [ "$remaining" -gt 0 ] || exit 4; ` +
    `nohup setsid timeout "$remaining" sh ${REMOTE_ROOT}/${args.windowId}/guard.sh </dev/null >/dev/null 2>&1 &`;
  return 'su -c ' + shellQuote(command);
}

// One adb call per read: the guard is polled while the device is under a fault,
// and nine separate `cat` round trips per poll would measure the host, not the
// device. Sections are delimited by a marker line this script never writes.
export function readGuardState({ serial, windowId, hardEpochMs = null }) {
  const dir = `${REMOTE_ROOT}/${windowId}`;
  const names = ['state', 'heartbeat', 'guard-pid', 'rules.txt', 'blocked-events.txt', 'rules-clean',
    'stop-precheck.txt', 'stop-outcome', 'stop-response.json', 'stop-verified', 'events.log', 'rules-restored-at', 'stop-started-at', 'stop-trigger'];
  let text = '';
  try {
    text = adb(serial, ['shell', `su -c 'for f in ${names.join(' ')}; do echo "@@$f"; cat ${dir}/$f 2>/dev/null; echo; done'`],
      { timeout: hardEpochMs ? Math.max(1, Math.min(20000, hardEpochMs - Date.now())) : 20000 });
  } catch { text = ''; }
  const sections = {};
  let current = null;
  for (const line of text.split(/\r?\n/)) {
    const marker = /^@@(.+)$/.exec(line.trim());
    if (marker) { current = marker[1]; sections[current] = []; continue; }
    if (current) sections[current].push(line);
  }
  const read = name => (sections[name] || []).join('\n').trim();
  const heartbeat = read('heartbeat');
  return {
    windowId,
    state: read('state') || null,
    heartbeatAtMs: /^[0-9]+$/.test(heartbeat) ? Number(heartbeat) : null,
    guardPid: read('guard-pid') || null,
    rules: read('rules.txt').split(/\r?\n/).map(line => line.trim()).filter(Boolean),
    blockedEvents: read('blocked-events.txt').split(/\r?\n/).map(line => line.trim()).filter(Boolean),
    rulesClean: read('rules-clean') || null,
    rulesRestoredAtMs: Number(read('rules-restored-at')) || null,
    stopStartedAtMs: Number(read('stop-started-at')) || null,
    stopTrigger: read('stop-trigger') || null,
    stopPrecheck: read('stop-precheck.txt') || null,
    stopOutcome: read('stop-outcome') || null,
    stopResponse: read('stop-response.json') || null,
    stopVerified: read('stop-verified') || null,
    events: read('events.log').split(/\r?\n/).map(line => line.trim()).filter(Boolean),
  };
}

export async function armDeviceGuard({ serial, args, waitMs = 15000 }) {
  args = normalizeArmArgs(args);
  if (serial !== args.serial) throw fail('ARGS', 'guard serial does not match its window');
  const script = buildGuardScript(args);
  const hostPath = path.join(root, '.runtime', 'tmp-b3', `guard-${args.windowId}.sh`);
  fs.mkdirSync(path.dirname(hostPath), { recursive: true });
  fs.writeFileSync(hostPath, script);
  adb(serial, ['shell', `mkdir -p ${REMOTE_ROOT}/${args.windowId}`]);
  adb(serial, ['push', hostPath, `${REMOTE_ROOT}/${args.windowId}/guard.sh`]);
  adb(serial, ['shell', `su -c 'chmod 755 ${REMOTE_ROOT}/${args.windowId}/guard.sh'`]);
  // LDPlayer's su/adbd otherwise retains the caller's input/session until the
  // background job exits. Detach the session and close all inherited streams;
  // the outer device timeout still owns the absolute hard deadline.
  adb(serial, ['shell', buildGuardLaunchCommand(args)]);
  const deadline = Date.now() + waitMs;
  let first = null, second = null;
  while (Date.now() < deadline) {
    const state = readGuardState({ serial, windowId: args.windowId });
    if (state.state === 'armed' && state.heartbeatAtMs) {
      if (first === null) first = state.heartbeatAtMs;
      else if (state.heartbeatAtMs > first) { second = state.heartbeatAtMs; break; }
    }
    await new Promise(resolve => setTimeout(resolve, 400));
  }
  return { ok: Boolean(second), scriptPath: hostPath, firstHeartbeatMs: first, secondHeartbeatMs: second,
    state: readGuardState({ serial, windowId: args.windowId }) };
}

const selftest = () => {
  const now = Date.now();
  const base = { windowId: '11111111-2222-4333-8444-555555555555', commandId: '66666666-7777-4888-9999-aaaaaaaaaaaa',
    serial: 'emulator-5558', accountRef: '3', ownerRef: 'owner:fixture', scan: true,
    startAtMs: now + 5000, deadlineMs: now + 20000, closeMs: now + 60000, hardMs: now + 95000,
    armedControlSeq: 109, armedGeneration: 'ba900bc0-7175-4521-8bff-aede4a268fe8' };
  const cases = [];
  try {
    const args = normalizeArmArgs(base);
    const script = buildGuardScript(args);
    cases.push(['script has no wi-fi control', !/svc wifi|wifi disable|wifi enable/.test(script)]);
    cases.push(['script never touches the global adb server', !/adb (kill-server|start-server)/.test(script)]);
    cases.push(['script blocks only the app uid', script.includes('owner != uid') && script.includes('APPUID=$(stat -c %u')]);
    cases.push(['script excludes 443 and loopback/private', script.includes('if (port == 443) next') && script.includes('if (ip1 == 127 || ip1 == 10) next')]);
    cases.push(['script fences the STOP by control sequence', script.includes('CONTROL_SEQ_MOVED') && script.includes('armedSeq')]);
    cases.push(['script removes every tuple it added', script.includes('done < "$OUT/rules.txt"') && script.includes('rules-clean')]);
    cases.push(['script has a hard exit', script.includes('HARD')]);
    cases.push(['restore and STOP are separate', script.includes('CLOSE=') && script.includes('recovery-observation') && script.includes('rules-restored-at')]);
    const launch = buildGuardLaunchCommand(args);
    cases.push(['launch detaches all streams and retains outer deadline', launch.includes('nohup setsid timeout "$remaining" sh') &&
      launch.includes('</dev/null >/dev/null 2>&1 &') && launch.includes(String(args.hardMs - args.clockOffsetMs))]);
    cases.push(['script quotes the account', script.includes("ACC='3'")]);
  } catch (error) { cases.push(['build', false, error.message]); }
  const rejects = (mutate) => {
    try { normalizeArmArgs({ ...base, ...mutate }); return false; } catch { return true; }
  };
  cases.push(['rejects a foreign serial', rejects({ serial: 'emulator-5554x' })]);
  cases.push(['rejects a past window', rejects({ startAtMs: now - 1 })]);
  cases.push(['rejects start after deadline', rejects({ deadlineMs: now + 4000 })]);
  cases.push(['rejects hard before deadline', rejects({ hardMs: now + 10000 })]);
  cases.push(['rejects no recovery observation time', rejects({ closeMs: now + 20000 })]);
  cases.push(['rejects insufficient STOP budget', rejects({ hardMs: now + 70000 })]);
  cases.push(['rejects a non-uuid window', rejects({ windowId: 'window-1' })]);
  cases.push(['rejects a huge horizon', rejects({ hardMs: now + 40 * 60_000, deadlineMs: now + 30 * 60_000 })]);
  const failed = cases.filter(([, ok]) => !ok).map(([name]) => name);
  console.log(JSON.stringify({ mode: 'selftest', cases: cases.length, failed }, null, 2));
  return failed.length ? 1 : 0;
};

export async function main(argv) {
  const mode = argv[0];
  const options = Object.fromEntries(argv.slice(1).filter(a => a.startsWith('--')).map(entry => {
    const [key, ...rest] = entry.replace(/^--/, '').split('=');
    return [key, rest.join('=')];
  }));
  if (mode === 'selftest') return selftest();
  if (mode === 'read') {
    const windowId = text(options['window-id'], 'window-id', UUID);
    const serial = text(options.serial || 'emulator-5558', 'serial', /^emulator-555[468]$/);
    console.log(JSON.stringify(readGuardState({ serial, windowId }), null, 2));
    return 0;
  }
  if (mode === 'arm') {
    let args;
    try {
      args = normalizeArmArgs({
        windowId: options['window-id'], commandId: options['command-id'], serial: options.serial,
        accountRef: options['account-ref'], ownerRef: options['owner-ref'], scan: options.scan,
        startAtMs: Number(options['start-epoch-ms']), deadlineMs: Number(options['deadline-epoch-ms']),
        closeMs: Number(options['close-epoch-ms']),
        clockOffsetMs: Number(options['clock-offset-ms'] || 0),
        hardMs: Number(options['hard-epoch-ms']), armedControlSeq: Number(options['armed-control-seq']),
        armedGeneration: options['armed-generation'],
      });
    } catch (error) {
      console.error(JSON.stringify({ ok: false, code: error.code || 'ARGS', message: error.message }));
      return 4;
    }
    const result = await armDeviceGuard({ serial: args.serial, args });
    console.log(JSON.stringify(result, null, 2));
    return result.ok ? 0 : 5;
  }
  console.error(JSON.stringify({ code: 'ARGS', message: 'mode must be selftest|arm|read' }));
  return 4;
}

if (process.argv[1] && process.argv[1].replace(/\\/g, '/').endsWith('coordination-zcode-device-guard.mjs')) {
  main(process.argv.slice(2)).then(code => { process.exitCode = code; })
    .catch(error => { console.error(JSON.stringify({ ok: false, code: error.code || 'ERROR', message: error.message })); process.exitCode = 1; });
}
