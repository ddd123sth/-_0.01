/* The selected artwork was exported at a 1260px browser viewport, so every narrower media block was
   inactive there; carrying them into a 390px WebView would silently swap in another design. */
function topItems(css) {
  const items = [];
  let i = 0;
  while (i < css.length) {
    while (i < css.length && /\s/.test(css[i])) i++;
    if (i >= css.length) break;
    if (css[i] === '/' && css[i + 1] === '*') { const end = css.indexOf('*/', i + 2); i = end < 0 ? css.length : end + 2; continue; }
    if (css[i] === '@') {
      const brace = css.indexOf('{', i);
      const params = css.slice(i, brace).trim();
      let depth = 0, j = brace;
      for (; j < css.length; j++) { if (css[j] === '{') depth++; else if (css[j] === '}') { depth--; if (!depth) break; } }
      items.push({ kind: 'at', params, body: css.slice(brace + 1, j) });
      i = j + 1;
      continue;
    }
    const brace = css.indexOf('{', i);
    if (brace < 0) break;
    const selector = css.slice(i, brace).trim();
    let j = brace + 1, depth = 1;
    while (j < css.length && depth) { if (css[j] === '{') depth++; else if (css[j] === '}') depth--; j++; }
    items.push({ kind: 'rule', selector, body: css.slice(brace + 1, j - 1).trim() });
    i = j;
  }
  return items;
}

const parts = [];
const stats = { sources: {}, kept: 0, dropped: 0, droppedMedia: [] };
for (const file of SHEET) {
  const text = readFileSync(join(DESIGN, file), 'utf8');
  stats.sources[file] = { bytes: Buffer.byteLength(text), sha256: createHash('sha256').update(text).digest('hex') };
  for (const item of topItems(text)) {
    if (item.kind === 'at') {
      const narrow = /@media[^{]*max-width\s*:/.test(item.params);
      if (narrow) { stats.droppedMedia.push(file + ' ' + item.params); stats.dropped++; continue; }
      if (/@media/.test(item.params)) {
        const inner = topItems(item.body).filter(one => one.kind === 'rule' && !isDropped(one.selector));
        if (!inner.length) continue;
        parts.push(item.params + '{' + inner.map(one => one.selector + '{' + one.body + '}').join('') + '}');
        stats.kept += inner.length;
        continue;
      }
      parts.push(item.params + '{' + item.body + '}');
      continue;
    }
    if (isDropped(item.selector)) { stats.dropped++; continue; }
    /* Only the design-studio font stack on <html> is replaced: the phone body keeps the prototype stack. */
    const body = item.body.replace(/url\(["']?assets\/garden-dawn\.png["']?\)/g, 'url("../brand/garden-moon.png")')
      .replace(/url\(["']?assets\//g, 'url("../brand/');
    parts.push(item.selector + '{' + body + '}');
    stats.kept++;
  }
}

